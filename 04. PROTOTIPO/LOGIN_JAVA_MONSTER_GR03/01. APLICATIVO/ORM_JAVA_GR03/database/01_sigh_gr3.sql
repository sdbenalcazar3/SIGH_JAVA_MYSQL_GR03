-- =====================================================================
-- SIGH_GR3 - Base de datos del Sistema de Gestion Hospitalaria (GR03)
-- Crea las tablas del subsistema de seguridad y personal usadas por
-- ORM_JAVA_GR03 y carga datos de prueba para el login.
-- Compatible con MySQL 8 y MariaDB 10.4 (XAMPP).
-- Importar desde phpMyAdmin: Importar > Seleccionar archivo > Continuar.
-- Usuarios de prueba (clave Sigh2026):
--   demo.sigh  -> perfil ADM, con la opcion DEP (departamentos)
--   luis.mora  -> perfil ENF, sin la opcion DEP
-- =====================================================================
CREATE DATABASE IF NOT EXISTS SIGH_GR3 CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE SIGH_GR3;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS SETOK_RECUPE, SEOXP_OPCPER, SEUXP_USUPER, SEOPC_OPCION, SEPER_PERFIL,
    SEUSU_USUARI, PEPER_PERSON, SESIS_SISTEM, SEEST_ESTADO, PECAR_CARGO, PEDEP_DEPART,
    PEEST_ESTADO, PEGEN_GENERO;
SET FOREIGN_KEY_CHECKS = 1;

-- ---------------------------- Catalogos ----------------------------
CREATE TABLE PEGEN_GENERO (
    PEGEN_CODIGO VARCHAR(1)   NOT NULL,
    PEGEN_NOMBRE VARCHAR(100) NOT NULL,
    PEGEN_ACTIVO BIT(1)       NOT NULL,
    PRIMARY KEY (PEGEN_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE PEEST_ESTADO (
    PEEST_CODIGO VARCHAR(1)   NOT NULL,
    PEEST_NOMBRE VARCHAR(100) NOT NULL,
    PEEST_ACTIVO BIT(1)       NOT NULL,
    PRIMARY KEY (PEEST_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE PEDEP_DEPART (
    PEDEP_CODIGO VARCHAR(3)   NOT NULL,
    PEDEP_NOMBRE VARCHAR(100) NOT NULL,
    PEDEP_ACTIVO BIT(1)       NOT NULL,
    PRIMARY KEY (PEDEP_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE PECAR_CARGO (
    PECAR_CODIGO VARCHAR(3)   NOT NULL,
    PECAR_NOMBRE VARCHAR(100) NOT NULL,
    PECAR_ACTIVO BIT(1)       NOT NULL,
    PRIMARY KEY (PECAR_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE SEEST_ESTADO (
    SEEST_CODIGO VARCHAR(1)   NOT NULL,
    SEEST_NOMBRE VARCHAR(100) NOT NULL,
    SEEST_ACTIVO BIT(1)       NOT NULL,
    PRIMARY KEY (SEEST_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE SESIS_SISTEM (
    SESIS_CODIGO VARCHAR(2)   NOT NULL,
    SESIS_NOMBRE VARCHAR(100) NOT NULL,
    SESIS_ACTIVO BIT(1)       NOT NULL,
    PRIMARY KEY (SESIS_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ---------------------------- Personal ----------------------------
CREATE TABLE PEPER_PERSON (
    PEPER_CODIGO VARCHAR(6)   NOT NULL,
    PEPER_CODEXT VARCHAR(10)  NOT NULL,
    PEPER_NOMBRE VARCHAR(255) NOT NULL,
    PEPER_APELLI VARCHAR(150) NOT NULL,
    PEPER_FUNCIO VARCHAR(255) NOT NULL,
    PEPER_HABILI VARCHAR(255) NULL,
    PEPER_ACTIVO BIT(1)       NOT NULL,
    PEPER_TIPDOC VARCHAR(30)  NULL,
    PEPER_NUMDOC VARCHAR(30)  NULL,
    PEPER_FECNAC DATE         NULL,
    PEPER_TELEFO VARCHAR(30)  NULL,
    PEPER_CORREO VARCHAR(150) NULL,
    PEGEN_CODIGO VARCHAR(1)   NULL,
    PEEST_CODIGO VARCHAR(1)   NULL,
    PEDEP_CODIGO VARCHAR(3)   NOT NULL,
    PECAR_CODIGO VARCHAR(3)   NOT NULL,
    PRIMARY KEY (PEPER_CODIGO),
    CONSTRAINT FK_PEPER_GENERO FOREIGN KEY (PEGEN_CODIGO) REFERENCES PEGEN_GENERO (PEGEN_CODIGO),
    CONSTRAINT FK_PEPER_ESTCIV FOREIGN KEY (PEEST_CODIGO) REFERENCES PEEST_ESTADO (PEEST_CODIGO),
    CONSTRAINT FK_PEPER_DEPART FOREIGN KEY (PEDEP_CODIGO) REFERENCES PEDEP_DEPART (PEDEP_CODIGO),
    CONSTRAINT FK_PEPER_CARGO  FOREIGN KEY (PECAR_CODIGO) REFERENCES PECAR_CARGO (PECAR_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ---------------------------- Seguridad ----------------------------
CREATE TABLE SEUSU_USUARI (
    SEUSU_CODIGO VARCHAR(6)   NOT NULL,
    SEUSU_USUARI VARCHAR(255) NOT NULL,
    SEUSU_HASHCL VARCHAR(255) NOT NULL,
    SEUSU_INTFAL INT          NOT NULL DEFAULT 0,
    SEUSU_BLOHAS DATETIME(6)  NULL,
    SEUSU_FECCRE DATETIME(6)  NOT NULL,
    SEUSU_FECMOD DATETIME(6)  NULL,
    SEUSU_PIEFIR VARCHAR(200) NULL,
    PEPER_CODIGO VARCHAR(6)   NOT NULL,
    SEEST_CODIGO VARCHAR(1)   NOT NULL,
    PRIMARY KEY (SEUSU_CODIGO),
    UNIQUE KEY UK_SEUSU_USUARI (SEUSU_USUARI),
    UNIQUE KEY UK_SEUSU_PERSONA (PEPER_CODIGO),
    CONSTRAINT FK_SEUSU_PERSONA FOREIGN KEY (PEPER_CODIGO) REFERENCES PEPER_PERSON (PEPER_CODIGO),
    CONSTRAINT FK_SEUSU_ESTADO  FOREIGN KEY (SEEST_CODIGO) REFERENCES SEEST_ESTADO (SEEST_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE SEPER_PERFIL (
    SEPER_CODIGO VARCHAR(3)   NOT NULL,
    SEPER_NOMBRE VARCHAR(255) NOT NULL,
    SEPER_ACTIVO BIT(1)       NOT NULL,
    SEPER_DESCRI TEXT         NULL,
    SEPER_OBSERV TEXT         NULL,
    SEEST_CODIGO VARCHAR(1)   NOT NULL,
    PRIMARY KEY (SEPER_CODIGO),
    CONSTRAINT FK_SEPER_ESTADO FOREIGN KEY (SEEST_CODIGO) REFERENCES SEEST_ESTADO (SEEST_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE SEOPC_OPCION (
    SEOPC_CODIGO VARCHAR(3)   NOT NULL,
    SEOPC_NOMBRE VARCHAR(100) NOT NULL,
    SEOPC_MODULO VARCHAR(255) NOT NULL,
    SEOPC_OPERAC VARCHAR(255) NOT NULL,
    SEOPC_DESCRI TEXT         NULL,
    SEOPC_ACTIVO BIT(1)       NOT NULL,
    SESIS_CODIGO VARCHAR(2)   NOT NULL,
    SEEST_CODIGO VARCHAR(1)   NOT NULL,
    PRIMARY KEY (SEOPC_CODIGO),
    CONSTRAINT FK_SEOPC_SISTEMA FOREIGN KEY (SESIS_CODIGO) REFERENCES SESIS_SISTEM (SESIS_CODIGO),
    CONSTRAINT FK_SEOPC_ESTADO  FOREIGN KEY (SEEST_CODIGO) REFERENCES SEEST_ESTADO (SEEST_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE SEUXP_USUPER (
    SEUXP_CODIGO        VARCHAR(6)   NOT NULL,
    SEUXP_DESDE         DATETIME(6)  NOT NULL,
    SEUXP_HASTA         DATETIME(6)  NULL,
    SEUXP_AMBITO        VARCHAR(255) NOT NULL,
    SEUXP_VIGENT        BIT(1)       NOT NULL,
    SEUSU_CODIGO        VARCHAR(6)   NOT NULL,
    SEPER_CODIGO        VARCHAR(3)   NOT NULL,
    SEUSU_CODIGO_ASIGNA VARCHAR(6)   NOT NULL,
    PRIMARY KEY (SEUXP_CODIGO),
    CONSTRAINT FK_SEUXP_USUARIO FOREIGN KEY (SEUSU_CODIGO) REFERENCES SEUSU_USUARI (SEUSU_CODIGO),
    CONSTRAINT FK_SEUXP_PERFIL  FOREIGN KEY (SEPER_CODIGO) REFERENCES SEPER_PERFIL (SEPER_CODIGO),
    CONSTRAINT FK_SEUXP_ASIGNA  FOREIGN KEY (SEUSU_CODIGO_ASIGNA) REFERENCES SEUSU_USUARI (SEUSU_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE SEOXP_OPCPER (
    SEOXP_CODIGO VARCHAR(6)   NOT NULL,
    SEOXP_AMBITO VARCHAR(255) NOT NULL,
    SEOXP_VIGENT BIT(1)       NOT NULL,
    SEOXP_DESDE  DATETIME(6)  NOT NULL,
    SEOXP_HASTA  DATETIME(6)  NULL,
    SEPER_CODIGO VARCHAR(3)   NOT NULL,
    SEOPC_CODIGO VARCHAR(3)   NOT NULL,
    SEUSU_CODIGO VARCHAR(6)   NOT NULL,
    PRIMARY KEY (SEOXP_CODIGO),
    CONSTRAINT FK_SEOXP_PERFIL   FOREIGN KEY (SEPER_CODIGO) REFERENCES SEPER_PERFIL (SEPER_CODIGO),
    CONSTRAINT FK_SEOXP_OPCION   FOREIGN KEY (SEOPC_CODIGO) REFERENCES SEOPC_OPCION (SEOPC_CODIGO),
    CONSTRAINT FK_SEOXP_CONCEDE  FOREIGN KEY (SEUSU_CODIGO) REFERENCES SEUSU_USUARI (SEUSU_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- Tokens de recuperacion de clave (login)
CREATE TABLE SETOK_RECUPE (
    SETOK_CODIGO BIGINT      NOT NULL AUTO_INCREMENT,
    SETOK_TOKEN  VARCHAR(64) NOT NULL,
    SETOK_FECCRE DATETIME    NOT NULL,
    SETOK_EXPIRA DATETIME    NOT NULL,
    SETOK_USADO  BIT(1)      NOT NULL DEFAULT b'0',
    SEUSU_CODIGO VARCHAR(6)  NOT NULL,
    PRIMARY KEY (SETOK_CODIGO),
    UNIQUE KEY UK_SETOK_TOKEN (SETOK_TOKEN),
    CONSTRAINT FK_SETOK_USUARIO FOREIGN KEY (SEUSU_CODIGO) REFERENCES SEUSU_USUARI (SEUSU_CODIGO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

