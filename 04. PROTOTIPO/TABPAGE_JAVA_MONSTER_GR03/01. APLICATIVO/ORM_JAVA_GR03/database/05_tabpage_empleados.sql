SET @col_foto = (
    SELECT COUNT(*)
    FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'PEPER_PERSON'
      AND COLUMN_NAME = 'PEPER_FOTO'
);
SET @sql_foto = IF(
    @col_foto = 0,
    'ALTER TABLE PEPER_PERSON ADD COLUMN PEPER_FOTO VARCHAR(255) NULL',
    'SELECT 1'
);
