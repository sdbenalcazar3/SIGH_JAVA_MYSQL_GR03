-- ---------------------------------------------------------------------
-- 2. Tabla hija: Datos Academicos (1:N con PEPER_PERSON)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PEACA_ACADEM (
    PEACA_CODIGO BIGINT       NOT NULL AUTO_INCREMENT,
    PEPER_CODIGO VARCHAR(6)   NOT NULL,
    PEACA_NIVEL  VARCHAR(60)  NOT NULL,
    PEACA_INSTIT VARCHAR(150) NOT NULL,
    PEACA_TITULO VARCHAR(150) NOT NULL,
    PRIMARY KEY (PEACA_CODIGO),
    KEY IX_PEACA_PERSONA (PEPER_CODIGO),
    CONSTRAINT FK_PEACA_PERSONA FOREIGN KEY (PEPER_CODIGO)
        REFERENCES PEPER_PERSON (PEPER_CODIGO) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ---------------------------------------------------------------------
-- 3. Tabla hija: Datos Familiares (1:N con PEPER_PERSON)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PEFAM_FAMILI (
    PEFAM_CODIGO BIGINT       NOT NULL AUTO_INCREMENT,
    PEPER_CODIGO VARCHAR(6)   NOT NULL,
    PEFAM_PARENT VARCHAR(60)  NOT NULL,
    PEFAM_APELLI VARCHAR(150) NOT NULL,
    PEFAM_NOMBRE VARCHAR(150) NOT NULL,
    PEFAM_FECNAC DATE         NULL,
    PRIMARY KEY (PEFAM_CODIGO),
    KEY IX_PEFAM_PERSONA (PEPER_CODIGO),
    CONSTRAINT FK_PEFAM_PERSONA FOREIGN KEY (PEPER_CODIGO)
        REFERENCES PEPER_PERSON (PEPER_CODIGO) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

-- ---------------------------------------------------------------------
-- 4. Registro de la opcion EMP (Empleados) en SEOPC_OPCION
-- ---------------------------------------------------------------------
INSERT INTO SEOPC_OPCION (
    SEOPC_CODIGO, SEOPC_NOMBRE, SEOPC_MODULO, SEOPC_OPERAC,
    SEOPC_DESCRI, SEOPC_ACTIVO, SESIS_CODIGO, SEEST_CODIGO
)
SELECT 'EMP', 'Empleados', 'Personal', 'Mantenimiento',
       'Mantenimiento de empleados con TabPage (datos generales, academicos y familiares)',
       1, 'SG', 'A'
FROM DUAL
WHERE NOT EXISTS (
    SELECT 1 FROM SEOPC_OPCION WHERE SEOPC_CODIGO = 'EMP'
);

-- ---------------------------------------------------------------------
-- 5. Concesion del permiso OPL003 (EMP) al perfil ADM
-- ---------------------------------------------------------------------
INSERT INTO SEOXP_OPCPER (
    SEOXP_CODIGO, SEOXP_AMBITO, SEOXP_VIGENT, SEOXP_DESDE, SEOXP_HASTA,
    SEPER_CODIGO, SEOPC_CODIGO, SEUSU_CODIGO
)
SELECT 'OPL003', 'Mantenimiento de empleados con TabPage', 1, NOW(), NULL,
       up.SEPER_CODIGO, 'EMP', up.SEUSU_CODIGO
FROM SEUXP_USUPER up
WHERE up.SEPER_CODIGO = 'ADM'
  AND up.SEUXP_VIGENT = 1
  AND up.SEUXP_HASTA IS NULL
  AND NOT EXISTS (SELECT 1 FROM SEOXP_OPCPER WHERE SEOPC_CODIGO = 'EMP' AND SEPER_CODIGO = 'ADM')
  AND NOT EXISTS (SELECT 1 FROM SEOXP_OPCPER WHERE SEOXP_CODIGO = 'OPL003')
ORDER BY up.SEUXP_CODIGO
LIMIT 1;

